package com.jinn.inputmethod

/**
 * 26 键字母右上角的角标映射（纯函数，键面绘制与长按上屏共用同一份，永不发叉）。
 *
 * 三排分别给「数字 / 中文标点与货币符 / 常用符号」，长按该键即上屏角标文字：
 * ```
 * q w e r t y u i o p     1 2 3 4 5 6 7 8 9 0
 * a s d f g h j k l       ，。$？！：；“”     （9 键）
 * z x c v b n m           （）、@#%&            （7 键）
 * ```
 * 只在中文拼音的字母层显示：英文态（字母就是正文）、大写锁定、符号层都不画。
 * 中文态下「小写长按转大写」本来就不生效（它只在英文态），两条长按不会抢手势。
 *
 * 与 [NumberRowLabels] 的分工：那边管数字行 10 个键的**主标签**（可自定义），
 * 这里管字母键的**次要角标**（固定表）。两者都遵守「显示即上屏」。
 */
object CornerLabels {

    /** 第 2 排（a..l，9 键）；D 键沿用幻影 26 键的 `$`，其余为中文标点 */
    private val ROW2 = listOf("，", "。", "$", "？", "！", "：", "；", "“", "”")

    /** 第 3 排（z..m，7 键） */
    private val ROW3 = listOf("（", "）", "、", "@", "#", "%", "&")

    /**
     * 取字母 [c] 的角标；不在 a..z 内返回空串。
     *
     * 用 `when` 显式列举而非 Map：调用点在重绘路径上（26 键 × 每帧），
     * 避免装箱查表；返回的都是常量池里的既有实例，不产生分配。
     */
    fun of(c: Char): String = when (c.lowercaseChar()) {
        'q' -> "1"
        'w' -> "2"
        'e' -> "3"
        'r' -> "4"
        't' -> "5"
        'y' -> "6"
        'u' -> "7"
        'i' -> "8"
        'o' -> "9"
        'p' -> "0"
        'a' -> ROW2[0]
        's' -> ROW2[1]
        'd' -> ROW2[2]
        'f' -> ROW2[3]
        'g' -> ROW2[4]
        'h' -> ROW2[5]
        'j' -> ROW2[6]
        'k' -> ROW2[7]
        'l' -> ROW2[8]
        'z' -> ROW3[0]
        'x' -> ROW3[1]
        'c' -> ROW3[2]
        'v' -> ROW3[3]
        'b' -> ROW3[4]
        'n' -> ROW3[5]
        'm' -> ROW3[6]
        else -> ""
    }

    /** 该键是否带角标（长按分支的判据，避免为空串排一次长按计时器） */
    fun has(c: Char): Boolean = of(c).isNotEmpty()
}
